"""Self-Replicating Code Generator (SRCG).

The defense is a real Python program, stored as a *generation file*. Every
generation file is a quine: it can print its own source exactly, without
reading itself from disk. It can also produce the source of its successor, a
copy of itself in which only the fork-choice policy is replaced.

SRCG writes the policy code (from a template, or with an LLM), checks it, asks
the current generation to reproduce with the new policy, and saves the result.

Only one function ever changes between generations:

    choose_branch(first_seen, later_seen, rng) -> first_seen or later_seen
"""
from __future__ import annotations

import ast
import hashlib
import os
import random
from dataclasses import dataclass
from typing import Callable, Optional

from .llm import LLM, strip_code_fences

_MARK = "@@" + "SELF" + "@@"
_BEGIN = "# --- POLICY " + "BEGIN ---"
_END = "# --- POLICY " + "END ---"

# Text of a generation file. The marker is replaced by the repr of this text
# itself, which is what lets the file reproduce its own source.
_GENERATION_TEMPLATE = '''#!/usr/bin/env python3
"""Self-evolving selfish-mining defense: one generation.

This file is a quine. `python <this file> --emit` prints its own source,
byte for byte, without reading the file. `evolve(policy)` returns the source of
the next generation: the same program with a new fork-choice policy.

Generated by the Self-Replicating Code Generator. Do not edit by hand.
"""
import hashlib
import sys

GENERATION = 0
PARENT_SHA256 = "none"

_T = ''' + _MARK + '''
_MARK = "@@" + "SELF" + "@@"
_BEGIN = "# --- POLICY " + "BEGIN ---"
_END = "# --- POLICY " + "END ---"

''' + _BEGIN + '''
P_SWITCH = 0.0


def choose_branch(first_seen, later_seen, rng):
    """During a tie, extend the later-seen branch with probability P_SWITCH."""
    if rng.random() < P_SWITCH:
        return later_seen
    return first_seen
''' + _END + '''


def source():
    """This program's own source code."""
    return _T.replace(_MARK, repr(_T))


def policy_source():
    """The evolvable part of this program."""
    return _T.split(_BEGIN + "\\n", 1)[1].split("\\n" + _END, 1)[0]


def evolve(new_policy):
    """Source code of the next generation, with `new_policy` as its policy."""
    head = _T.split(_BEGIN + "\\n", 1)[0]
    tail = _T.split("\\n" + _END, 1)[1]
    t = head + _BEGIN + "\\n" + new_policy.strip("\\n") + "\\n" + _END + tail
    t = t.replace("GENERATION = %d\\n" % GENERATION, "GENERATION = %d\\n" % (GENERATION + 1), 1)
    digest = hashlib.sha256(source().encode()).hexdigest()
    t = t.replace('PARENT_SHA256 = "%s"\\n' % PARENT_SHA256, 'PARENT_SHA256 = "%s"\\n' % digest, 1)
    return t.replace(_MARK, repr(t))


if __name__ == "__main__":
    if "--emit" in sys.argv:
        sys.stdout.write(source())
    else:
        print("generation %d, parent %s" % (GENERATION, PARENT_SHA256[:12]))
        print(policy_source())
'''

GENESIS_SOURCE = _GENERATION_TEMPLATE.replace(_MARK, repr(_GENERATION_TEMPLATE))


def policy_template(p_switch: float) -> str:
    """Policy code for 'switch to the later-seen branch with probability p'."""
    return (
        f"P_SWITCH = {p_switch!r}\n\n\n"
        "def choose_branch(first_seen, later_seen, rng):\n"
        '    """During a tie, extend the later-seen branch with probability P_SWITCH."""\n'
        "    if rng.random() < P_SWITCH:\n"
        "        return later_seen\n"
        "    return first_seen"
    )


# ---- validation of policy code ------------------------------------------------
class PolicyRejected(Exception):
    pass


_ALLOWED_NODES = (
    ast.Module, ast.FunctionDef, ast.arguments, ast.arg, ast.Return, ast.If, ast.IfExp,
    ast.Assign, ast.Expr, ast.Compare, ast.BoolOp, ast.BinOp, ast.UnaryOp, ast.Name,
    ast.Constant, ast.Call, ast.Attribute, ast.Load, ast.Store,
    ast.And, ast.Or, ast.Not, ast.USub, ast.UAdd,
    ast.Add, ast.Sub, ast.Mult, ast.Div,
    ast.Lt, ast.LtE, ast.Gt, ast.GtE, ast.Eq, ast.NotEq,
)


def validate_policy(code: str, trials: int = 4000) -> float:
    """Check policy code before it is allowed into a generation.

    Static check: the code may only contain a small subset of Python - constants,
    arithmetic, comparisons, if/else, and calls to rng.random(). No imports, no
    loops (so it always terminates), no attribute access other than rng.random.
    Behavioural check: called many times, it must always return one of the two
    branches it was given.

    Returns the measured probability of choosing the later-seen branch.
    """
    for forbidden in (_MARK, _BEGIN, _END, "__"):
        if forbidden in code:
            raise PolicyRejected(f"policy contains forbidden text {forbidden!r}")
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        raise PolicyRejected(f"syntax error: {e.msg}") from None

    functions = [n for n in tree.body if isinstance(n, ast.FunctionDef)]
    if [f.name for f in functions] != ["choose_branch"]:
        raise PolicyRejected("policy must define exactly one function, choose_branch")
    if [a.arg for a in functions[0].args.args] != ["first_seen", "later_seen", "rng"]:
        raise PolicyRejected("choose_branch must take (first_seen, later_seen, rng)")

    for node in ast.walk(tree):
        if not isinstance(node, _ALLOWED_NODES):
            raise PolicyRejected(f"{type(node).__name__} is not allowed in a policy")
        if isinstance(node, ast.Attribute):
            if not (isinstance(node.value, ast.Name) and node.value.id == "rng" and node.attr == "random"):
                raise PolicyRejected("the only attribute a policy may use is rng.random")
        if isinstance(node, ast.Call):
            f = node.func
            if not (isinstance(f, ast.Attribute) and node.args == [] and node.keywords == []):
                raise PolicyRejected("the only call a policy may make is rng.random()")
        if isinstance(node, ast.Expr) and not (isinstance(node.value, ast.Constant) and isinstance(node.value.value, str)):
            raise PolicyRejected("bare expressions are not allowed in a policy")

    namespace: dict = {"__builtins__": {}}
    try:
        exec(compile(tree, "<policy>", "exec"), namespace)      # restricted subset, no builtins
        fn = namespace["choose_branch"]
        rng = random.Random(12345)
        switched = 0
        for i in range(trials):
            first, later = ("pool", "honest") if i % 2 else ("honest", "pool")
            out = fn(first, later, rng)
            if out not in (first, later):
                raise PolicyRejected("choose_branch returned something other than a branch")
            switched += out == later
    except PolicyRejected:
        raise
    except Exception as e:
        raise PolicyRejected(f"policy failed when executed: {type(e).__name__}") from None
    return switched / trials


# ---- generations ---------------------------------------------------------------
@dataclass
class Generation:
    number: int
    path: str
    source: str
    sha256: str
    policy: Callable
    measured_p_switch: float
    _evolve: Callable[[str], str]


def load_generation(source: str, path: str = "<generation>") -> Generation:
    """Execute a generation's source and wrap what the framework needs from it."""
    ns: dict = {"__name__": "generation"}
    exec(compile(source, path, "exec"), ns)                     # the trusted core + a validated policy
    if ns["source"]() != source:
        raise ValueError("generation is not a quine: it does not reproduce its own source")
    return Generation(
        number=ns["GENERATION"], path=path, source=source,
        sha256=hashlib.sha256(source.encode()).hexdigest(),
        policy=ns["choose_branch"],
        measured_p_switch=validate_policy(ns["policy_source"]()),
        _evolve=ns["evolve"],
    )


class SelfReplicatingCodeGenerator:
    SYSTEM = (
        "You write one small Python function for a blockchain node. Output only code.\n"
        "Define exactly: def choose_branch(first_seen, later_seen, rng)\n"
        "It must return first_seen or later_seen. rng.random() gives a float in [0, 1).\n"
        "Allowed: constants, module-level constant assignments, arithmetic, comparisons, "
        "if/else, and rng.random(). No imports, loops, other calls, or other attributes."
    )

    def __init__(self, workdir: str, llm: Optional[LLM] = None):
        self.workdir = workdir
        self.llm = llm
        self.rejected = 0
        os.makedirs(workdir, exist_ok=True)

    def genesis(self) -> Generation:
        return self._save(GENESIS_SOURCE, 0)

    def write_policy(self, p_switch: float, context: str = "") -> str:
        """Policy code for the requested behaviour. Uses the LLM when one is
        configured and its answer passes validation and matches the request;
        otherwise uses the template."""
        if self.llm is not None:
            request = (f"The function must choose later_seen with probability {p_switch} "
                       f"and first_seen otherwise.\n{context}")
            try:
                code = strip_code_fences(self.llm(self.SYSTEM, request))
                if abs(validate_policy(code) - p_switch) <= 0.05:
                    return code
                raise PolicyRejected("behaviour does not match the request")
            except Exception:
                self.rejected += 1
        return policy_template(p_switch)

    def reproduce(self, parent: Generation, policy_code: str) -> Generation:
        """Ask the parent generation to produce its successor, then verify and save it."""
        validate_policy(policy_code)
        child_source = parent._evolve(policy_code)
        child = self._save(child_source, parent.number + 1)
        if child.number != parent.number + 1:
            raise ValueError("successor has the wrong generation number")
        return child

    def _save(self, source: str, number: int) -> Generation:
        path = os.path.join(self.workdir, f"gen_{number:04d}.py")
        gen = load_generation(source, path)       # raises if it is not a valid quine
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8", newline="") as f:
            f.write(source)
        os.replace(tmp, path)                      # atomic
        return gen
